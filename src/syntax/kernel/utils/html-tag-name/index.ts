/**
 * List of lowercase HTML “raw” tag names.
 *
 * The list, when parsing HTML (flow), results in HTML that can include lines
 * without exiting, until a closing tag also in this list is found (condition
 * 1).
 *
 * This module is copied from:
 * <https://spec.commonmark.org/0.30/#html-blocks>.
 *
 * > 👉 **Note**: `textarea` was added in `CommonMark@0.30`.
 */
export const htmlRawNames = ['pre', 'script', 'style', 'textarea'];

/**
 * Kagami: what a tag on Kagami's list means, for its lowercase name, or `undefined` for any
 * other tag. A tag is on the list when it names a void element of HTML, complete in one token,
 * whose effect Markdown lacks (private-docs/rules/html-tokens.md, decided by Kk Shinkai,
 * 2026-10-13).
 */
export function htmlReadTag(name: string): 'lineBreak' | 'image' | undefined {
  switch (name) {
    case 'br':
      return 'lineBreak';
    case 'img':
      return 'image';
    default:
      return undefined;
  }
}
